"""
Определение «это перевод самому себе».

Переводы между своими счетами в разных банках попадают в обе выписки: расходом
в одной и доходом в другой. Если считать их обычными операциями, месячные суммы
раздуваются с обеих сторон (на реальных данных пользователя это половина
«расходов»), лимиты срываются, прогноз и ИИ-разбор врут.

Опознаём двумя способами:
  * структурная пометка самого банка («Перевод собственных средств»,
    «Внутрибанковский перевод между счетами») — разбирается в парсере банка;
  * имя контрагента совпадает с владельцем счёта из шапки выписки — это здесь.
"""
import re

_WORD_RE = re.compile(r"[А-Яа-яЁёA-Za-z]{2,}")


def name_tokens(name: str) -> set[str]:
    """Слова имени без инициалов: «Мак М. Е.» -> {«мак»}."""
    return {w.lower().replace("ё", "е") for w in _WORD_RE.findall(name or "")}


def is_same_person(counterparty: str, owner: str, min_tokens: int = 2) -> bool:
    """Контрагент — это сам владелец счёта?

    Сравниваем по словам, инициалы игнорируем: в выписках владелец записан как
    «Мак Матвей Евгеньевич», а контрагент как «Матвей Евгеньевич М.».
    Нужно совпадение минимум двух полных слов, иначе однофамилец или просто
    тёзка считался бы своим же счётом.
    """
    if not counterparty or not owner:
        return False
    mine = name_tokens(owner)
    theirs = name_tokens(counterparty)
    if not theirs:
        return False
    common = theirs & mine
    return len(common) >= min_tokens and common == theirs


def normalize_phone(raw: str) -> str:
    """+7 (996) 593-36-13 и +79965933613 -> 79965933613."""
    digits = re.sub(r"\D", "", raw or "")
    if len(digits) == 11 and digits.startswith("8"):
        digits = "7" + digits[1:]
    return digits
