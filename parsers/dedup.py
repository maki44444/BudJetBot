"""Хэш строки выписки — защита от повторного импорта одного и того же файла
на уровне БД (уникальный индекс transactions(telegram_id, import_hash)).

Хэш обязан различать РАЗНЫЕ операции и совпадать у ОДНОЙ И ТОЙ ЖЕ операции,
импортированной повторно. Поэтому:
  * если банк даёт номер операции (external_id) — он идёт в ключ вместе
    с датой и суммой. Одного номера мало, и это видно на реальных выписках:
    у внутренних операций Ozon Банка номер короткий и сквозной («3», «4», «186»),
    а Альфа-Банк проводит под одним кодом сразу несколько операций (погашение
    долга 66,00 и процентов по нему 0,08 — код TIRR#26062001875 на обеих).
    Без даты и суммы вторая операция молча сошла бы за дубликат и потерялась.
    Дата и сумма у одной и той же операции не меняются, поэтому повторный
    импорт того же файла по-прежнему даёт тот же хэш;
  * иначе берётся время с точностью до секунды, а не дата, плюс сумма
    и описание. Дата целиком склеивала бы две одинаковые покупки за день
    в одну, и вторая молча терялась бы.
"""
import hashlib
from datetime import datetime
from decimal import Decimal


def compute_import_hash(
    bank: str,
    occurred_at: datetime,
    amount: Decimal,
    raw_description: str,
    external_id: str | None = None,
) -> str:
    if external_id:
        key = f"{bank}|id:{external_id.strip()}|{occurred_at:%Y-%m-%d}|{amount}"
    else:
        key = (
            f"{bank}|{occurred_at.isoformat()}|{amount}|{raw_description.strip().lower()}"
        )
    return hashlib.sha256(key.encode("utf-8")).hexdigest()
